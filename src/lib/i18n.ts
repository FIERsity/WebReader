const dictionaries = { zh, en };
export type TranslationKey = keyof typeof zh;

export function resolveLanguage(stored: string | null): Language {
  return stored === "en" ? "en" : "zh";
}

export function translate(language: Language, key: TranslationKey, variables: TranslationVariables = {}): string {
  const template = dictionaries[language][key];
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(variables[name] ?? `{${name}}`));
}
